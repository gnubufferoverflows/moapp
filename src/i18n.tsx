const LanguageContext = createContext<LanguageContextValue | null>(null)

export function translate(language: Language, key: TranslationKey, variables: Variables = {}) {
  const template: string = language === 'zh' ? zh[key] : en[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`))
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => localStorage.getItem('mo-language') === 'zh' ? 'zh' : 'en')

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
    try { localStorage.setItem('mo-language', language) } catch { /* Language persistence is optional. */ }
  }, [language])

  const t = useCallback((key: TranslationKey, variables: Variables = {}) => translate(language, key, variables), [language])

  const value = useMemo(() => ({ language, setLanguage, t }), [language, t])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}
